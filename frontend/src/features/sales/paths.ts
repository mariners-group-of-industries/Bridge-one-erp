  deliveries: `${BASE}/deliveries`,
  deliveryTab: (tab: "approved" | "deliveries" | "exchanges" | "challans") => `${BASE}/deliveries?tab=${tab}`,
  deliverOrder: (orderId: string) => `${BASE}/deliveries/new?order=${orderId}`,
  newDirectDelivery: `${BASE}/deliveries/new`,
  newExchange: `${BASE}/deliveries/exchange`,
  delivery: (id: string) => `${BASE}/deliveries/${id}`,
  editDelivery: (id: string) => `${BASE}/deliveries/${id}/edit`,
  printDelivery: (id: string, doc: "challan" | "challan-plain" | "mushak" | "invoice") => `/print/sales/deliveries/${id}?doc=${doc}`,
  returns: `${BASE}/returns`,
  returnTab: (tab: "deliveries" | "returns" | "market") => `${BASE}/returns?tab=${tab}`,
